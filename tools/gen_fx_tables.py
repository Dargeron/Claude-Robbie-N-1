#!/usr/bin/env python3
"""Generate game/sim/fx_tables.gd: integer trig tables for the deterministic sim.

The simulation never calls floating-point sin/cos/atan at runtime. These tables
are generated once, committed, and identical on every platform.

Angles use 4096 units per turn. Trig values are scaled by 16384.
Run from the repo root:  python3 tools/gen_fx_tables.py
"""
import math
from pathlib import Path

TURN = 4096
QUARTER = TURN // 4
TRIG_ONE = 16384
ATAN_STEPS = 1024

sin_q = [round(TRIG_ONE * math.sin(i * 2 * math.pi / TURN)) for i in range(QUARTER + 1)]
# ATAN[i] = angle units for ratio i/ATAN_STEPS, range 0..TURN/8
atan = [round(math.atan(i / ATAN_STEPS) * TURN / (2 * math.pi)) for i in range(ATAN_STEPS + 1)]


def fmt(name, values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("\t" + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return f"const {name}: Array[int] = [\n" + "\n".join(lines) + "\n]\n"


out = (
    "# GENERATED by tools/gen_fx_tables.py. Do not edit by hand.\n"
    "class_name FxTables\nextends RefCounted\n\n"
    f"## round(16384 * sin(i * tau / 4096)) for i in 0..{QUARTER}\n"
    + fmt("SIN_Q", sin_q)
    + f"\n## round(atan(i / {ATAN_STEPS}) * 4096 / tau) for i in 0..{ATAN_STEPS}\n"
    + fmt("ATAN", atan)
)
path = Path(__file__).resolve().parent.parent / "game" / "sim" / "fx_tables.gd"
path.write_text(out)
print(f"wrote {path} ({len(sin_q)} sin entries, {len(atan)} atan entries)")
